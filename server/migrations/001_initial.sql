CREATE TABLE users (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  account_type text NOT NULL CHECK (account_type IN ('customer', 'merchant')),
  is_admin boolean NOT NULL DEFAULT false,
  document_number text,
  document_type text CHECK (document_type IN ('cpf', 'cnpj')),
  phone text,
  address text
);

CREATE TABLE stores (
  id text PRIMARY KEY,
  owner_id uuid UNIQUE REFERENCES users(id),
  name text NOT NULL,
  address text NOT NULL DEFAULT ''
);

CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);

CREATE INDEX sessions_user_id_idx ON sessions(user_id);

CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id text REFERENCES stores(id),
  name text NOT NULL,
  category text NOT NULL,
  price numeric(12, 2) NOT NULL CHECK (price >= 0),
  original_price numeric(12, 2) CHECK (original_price >= 0),
  rating numeric(2, 1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
  reviews integer NOT NULL DEFAULT 0 CHECK (reviews >= 0),
  image text NOT NULL,
  badge text,
  featured boolean NOT NULL DEFAULT false,
  condition text CHECK (condition IN ('novo', 'seminovo', 'usado')),
  description text NOT NULL,
  stock integer NOT NULL DEFAULT 10 CHECK (stock >= 0),
  sku text,
  brand text,
  warranty_months integer NOT NULL DEFAULT 12 CHECK (warranty_months >= 0),
  delivery_days integer NOT NULL DEFAULT 3 CHECK (delivery_days >= 1),
  free_shipping boolean NOT NULL DEFAULT false,
  sold_count integer NOT NULL DEFAULT 0 CHECK (sold_count >= 0)
);

CREATE INDEX products_store_id_idx ON products(store_id);
